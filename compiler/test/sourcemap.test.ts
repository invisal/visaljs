import { describe, expect, it } from "vitest";

import { parseModule } from "../src/frontend/adapter.ts";
import { SourceMap } from "../src/frontend/sourcemap.ts";

/* bundle:                        originals:
 * 1 //#region b.js
 * 2 function sum$1(a, b) {        b.js 1: export function sum(a, b) {
 * 3 	return a + b;                b.js 2:   return a + b;
 * 4 }
 * 5 print(sum$1(1, 2));           a.js 3: print(sum(1, 2));
 */
const MAP = JSON.stringify({
  version: 3,
  sources: ["/src/b.js", "/src/a.js"],
  names: ["sum"],
  // line 2: col 0 → b.js 1:0; col 9 → b.js 1:16 named "sum"; line 3: col 1 → b.js 2:2;
  // line 5: col 0 → a.js 3:0; col 6 → a.js 3:6 named "sum"
  mappings: ";AAAA,SAAgBA;CACd;;ACCF,MAAMA",
});

describe("source maps", () => {
  const map = new SourceMap(MAP, (s) => s.replace("/src/", ""));

  it("maps bundle positions to the segment at or before them", () => {
    expect(map.original(2, 1)).toEqual({ file: "b.js", line: 1, column: 1 });
    expect(map.original(2, 12)).toEqual({ file: "b.js", line: 1, column: 17 });
    expect(map.original(3, 1)).toEqual({ file: "b.js", line: 2, column: 3 });  // before the first segment: the line's first
    expect(map.original(5, 7)).toEqual({ file: "a.js", line: 3, column: 7 });
    expect(map.original(1, 1)).toBeNull();  // generated by the bundler
    expect(map.original(4, 1)).toBeNull();
  });

  it("restores the original name of an identifier exactly at a named segment", () => {
    expect(map.originalName(2, 10)).toBe("sum");
    expect(map.originalName(2, 11)).toBeUndefined();
    expect(map.originalName(2, 1)).toBeUndefined();
  });

  it("gives the parsed module original locations, and renamed identifiers their original names", () => {
    const p = parseModule("//#region b.js\nfunction sum$1(a, b) {\n\treturn a + b;\n}\nprint(sum$1(1, 2));\n", "bundle.js", map);
    expect(p.body[0]).toMatchObject({ type: "FunctionDeclaration", loc: { file: "b.js", line: 1 }, id: { name: "sum$1", original: "sum" } });
    expect(p.body[1]!.loc).toEqual({ file: "a.js", line: 3, column: 1 });
  });
});
