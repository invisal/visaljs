// Generates runtime/src/tls_roots.gen.h: the root certificates node:tls trusts by default, as
// the Node running this script bundles them (Mozilla's CA list): tls.rootCertificates, PEM.
//
//   node runtime/tools/gen_tls_roots.mjs > runtime/src/tls_roots.gen.h
import process from "node:process";
import { rootCertificates } from "node:tls";

const out = [];
out.push(`/* Generated by runtime/tools/gen_tls_roots.mjs from Node ${process.version}'s tls.rootCertificates. Do not edit. */`);
out.push("/* Mozilla's CA certificate list (MPL 2.0): runtime/third_party/mozilla-ca. */");
out.push("static const char *const tls_root_pems[] = {");
for (const pem of rootCertificates) {
  const lines = pem.split("\n");
  out.push(lines.map((l, i) => `    "${l}${i < lines.length - 1 ? "\\n" : ""}"`).join("\n") + ",");
}
out.push("};");
process.stdout.write(out.join("\n") + "\n");
