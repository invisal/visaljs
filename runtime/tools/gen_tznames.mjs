// Generates runtime/src/tznames.gen.h: each IANA time zone's English names, standard and
// daylight, as Date.prototype.toString shows them in parentheses ("Western European Standard
// Time"). The names come from the ICU data of the Node running this script; the zone ids are
// those of the system's tz database (aliases included) that ICU knows.
//
//   node runtime/tools/gen_tznames.mjs > runtime/src/tznames.gen.h
import { existsSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import process from "node:process";

const ZONEINFO = "/usr/share/zoneinfo";

function zoneIds() {
  const ids = new Set(Intl.supportedValuesOf("timeZone"));
  const walk = (dir, prefix) => {
    for (const name of readdirSync(dir)) {
      if (!prefix && (name === "posix" || name === "right")) continue;  /* copies of the same zones */
      const full = join(dir, name);
      const id = prefix ? `${prefix}/${name}` : name;
      if (statSync(full).isDirectory()) walk(full, id);
      else if (/^[A-Z]/.test(name)) ids.add(id);
    }
  };
  if (existsSync(ZONEINFO)) walk(ZONEINFO, "");
  return [...ids].filter((id) => {
    try {
      new Intl.DateTimeFormat("en-US", { timeZone: id });
      return true;
    } catch {
      return false;
    }
  });
}

function nameAndOffset(id, date) {
  const part = (style) =>
    new Intl.DateTimeFormat("en-US", { timeZone: id, timeZoneName: style }).formatToParts(date).find((p) => p.type === "timeZoneName").value;
  return { name: part("long"), offset: part("longOffset") };
}

const toMinutes = (gmt) => {
  const m = /^GMT(?:([+-])(\d\d):(\d\d))?$/.exec(gmt);
  return m && m[1] ? (m[1] === "-" ? -1 : 1) * (Number(m[2]) * 60 + Number(m[3])) : 0;
};

export function generate() {
  const zones = [];
  const names = [];
  const index = new Map();
  const intern = (s) => {
    if (!index.has(s)) {
      index.set(s, names.length);
      names.push(s);
    }
    return index.get(s);
  };
  for (const id of zoneIds().sort()) {
    const jan = nameAndOffset(id, new Date(Date.UTC(2025, 0, 15)));
    const jul = nameAndOffset(id, new Date(Date.UTC(2025, 6, 15)));
    const [std, dst] = toMinutes(jan.offset) <= toMinutes(jul.offset) ? [jan, jul] : [jul, jan];
    zones.push([id, intern(std.name), intern(dst.name)]);
  }
  const lines = [
    `/* Generated by runtime/tools/gen_tznames.mjs from the ICU data of Node ${process.version}. Do not edit. */`,
    "/* CLDR data, Copyright Unicode, Inc. (Unicode License v3): runtime/third_party/unicode/LICENSE. */",
    "/* Each zone's standard and daylight names (indices into tz_names), sorted by zone id. */",
    "static const char *const tz_names[] = {",
    ...names.map((n) => `    "${n}",`),
    "};",
    "static const struct TzZone { const char *id; uint16_t std, dst; } tz_zones[] = {",
    ...zones.map(([id, s, d]) => `    { "${id}", ${s}, ${d} },`),
    "};",
  ];
  return lines.join("\n") + "\n";
}

if (process.argv[1] === import.meta.filename) process.stdout.write(generate());
